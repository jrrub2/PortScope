const DICTS = { en, id, es, ja, zh };
const FALLBACK = en;
const STORAGE_KEY = 'portscope.lang';
const listeners = new Set();
let current = 'en';

function formatValue(template, params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => (params[key] != null ? String(params[key]) : match));
}

export function getLocale() {
  return current;
}

export function getLanguages() {
  return LANGUAGES;
}

export function isSupportedLocale(locale) {
  return typeof locale === 'string' && Object.prototype.hasOwnProperty.call(DICTS, locale);
}

export function resolveInitialLocale() {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (isSupportedLocale(saved)) return saved;
  } catch (err) { /* storage blocked */ }
  return 'en';
}

export function setLocale(locale) {
  const next = isSupportedLocale(locale) ? locale : 'en';
  current = next;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = next;
  }
  listeners.forEach((fn) => {
    try { fn(next); } catch (err) { /* noop */ }
  });
  return next;
}

export function onLocaleChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function persistLocale(locale) {
  try { window.localStorage.setItem(STORAGE_KEY, locale); } catch (err) { /* noop */ }
}

export function t(key, params) {
  const dict = DICTS[current] || FALLBACK;
  const entry = dict[key] != null ? dict[key] : FALLBACK[key];
  if (entry == null) return key;
  if (typeof entry === 'string') return formatValue(entry, params);
  const other = entry.other || Object.values(entry)[0] || key;
  return formatValue(other, params);
}

export function tp(key, count, params) {
  const dict = DICTS[current] || FALLBACK;
  const entry = dict[key] != null ? dict[key] : FALLBACK[key];
  if (entry == null) return key;
  if (typeof entry === 'string') return formatValue(entry, { count, ...params });
  let category = 'other';
  try {
    category = new Intl.PluralRules(current).select(Number(count) || 0);
  } catch (err) {
    category = Number(count) === 1 ? 'one' : 'other';
  }
  const template = entry[category] || entry.other || Object.values(entry)[0] || key;
  return formatValue(template, { count, ...params });
}

/** Locale-aware number formatting. */
export function n(value, options) {
  try {
    return new Intl.NumberFormat(current, options).format(Number(value) || 0);
  } catch (err) {
    return String(value);
  }
}

export function applyStaticTranslations(root) {
  if (typeof document === 'undefined') return;
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach((el) => {
    const text = t(el.getAttribute('data-i18n'));
    if (el.textContent !== text) el.textContent = text;
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  scope.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  scope.querySelectorAll('[data-i18n-tooltip]').forEach((el) => {
    el.setAttribute('data-tooltip', t(el.getAttribute('data-i18n-tooltip')));
  });
}

